/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * BUILD THE SIGN-IN BACKDROP into the Keycloak login theme.
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 *   pnpm --filter @ind-core/web build-login-theme
 *
 * Bundles `src/spine/void/login-backdrop.ts` — and, through it, the floor-plan geometry, the
 * traced plan data and three.js — into a single classic script at
 * `infra/keycloak-themes/indcore/login/resources/js/backdrop.js`.
 *
 * That folder sits BESIDE `infra/keycloak/` rather than inside it: `infra/keycloak/` is
 * mounted as Keycloak's realm-import directory, and a theme tree buried in the pile of files
 * the server scans for realms to import is a thing somebody will eventually try to import.
 *
 * ───────────────────────────────────────────────────────────────────────────────
 * WHY A SEPARATE BUILD RATHER THAN NEXT'S
 * ───────────────────────────────────────────────────────────────────────────────
 * The login page is not ours. Keycloak renders it from a FreeMarker template and serves its
 * assets from the theme folder; Next never sees that request and cannot emit into it. So the
 * one file Keycloak needs is produced here, by the smallest tool that will do it.
 *
 * ───────────────────────────────────────────────────────────────────────────────
 * WHY THE OUTPUT IS COMMITTED
 * ───────────────────────────────────────────────────────────────────────────────
 * Keycloak reads the theme straight off a mounted folder. There is no build step between
 * this repository and a running container, so the artefact has to exist in the repository or
 * the container has nothing to serve. Re-run this whenever the geometry or the entry point
 * changes — nothing runs it for you, which is exactly why it prints the source it read and
 * the bytes it wrote.
 *
 * IIFE, not ESM: `properties.scripts` renders a plain `<script src>` with no `type=module`,
 * so an ESM bundle would be parsed as a classic script and die on its first `import`.
 */

import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, resolve, relative } from "node:path";
import { readFileSync, statSync, writeFileSync } from "node:fs";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, "../..");
const repoRoot = resolve(webRoot, "../..");

const JS_DIR = resolve(repoRoot, "infra/keycloak-themes/indcore/login/resources/js");

/**
 * TWO bundles, and the split is the point rather than an optimisation.
 *
 * `backdrop-loader.js` is what the theme's blocking `<script>` tag actually points at, so it
 * has to stay tiny. `backdrop.js` is the scene — half a megabyte of three.js — and the
 * loader fetches it asynchronously, after deciding the machine can use it. See the reasoning
 * block in `login-loader.ts`.
 */
const BUNDLES = [
  { entry: "src/spine/void/login-loader.ts", out: "backdrop-loader.js" },
  { entry: "src/spine/void/login-backdrop.ts", out: "backdrop.js" },
];

for (const b of BUNDLES) {
  const entry = resolve(webRoot, b.entry);
  const outfile = resolve(JS_DIR, b.out);

  const result = await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    minify: true,
    // Classic script. See the note above.
    format: "iife",
    platform: "browser",
    // A sign-in page is the one screen that cannot choose its browser. es2019 clears every
    // evergreen release by a wide margin and costs nothing here — the big bundle is
    // dominated by three.js, not by syntax.
    target: ["es2019"],
    legalComments: "none",
    banner: {
      js: "/* XELOR sign-in backdrop — GENERATED by apps/web/scripts/build/build-login-theme.mjs. Do not edit. */",
    },
    metafile: true,
    logLevel: "warning",
  });

  // Three.js embeds GLSL as multiline strings. Some upstream shader lines contain trailing
  // spaces, which are harmless in a browser but make the generated artefact fail this
  // repository's whitespace gate. Normalize the bundle after esbuild so rebuilding it is
  // deterministic and `git diff --check` stays meaningful.
  const generated = readFileSync(outfile, "utf8");
  const normalized = generated.replace(/[\t ]+$/gm, "");
  if (generated !== normalized) writeFileSync(outfile, normalized);

  const bytes = statSync(outfile).size;
  const inputs = Object.keys(result.metafile.inputs).length;
  console.log(
    `  ${b.out.padEnd(20)} ${String(inputs).padStart(3)} modules   ` +
      `${(bytes / 1024).toFixed(1).padStart(7)} kB minified   ← ${b.entry}`,
  );
}

console.log(`  into    ${relative(repoRoot, JS_DIR)}`);
